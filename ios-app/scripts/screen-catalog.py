#!/usr/bin/env python3
"""Generate snapshot factories from selected previews and publish validated test captures."""
import argparse
import json
from pathlib import Path
import re
import shutil
import struct
import textwrap
import zlib

APP_ROOT = Path(__file__).resolve().parents[1]
START = '// BEGIN GENERATED SNAPSHOT CATALOG'
END = '// END GENERATED SNAPSHOT CATALOG'
DECLARATION = re.compile(r'#Preview\("([a-z0-9]+(?:[.-][a-z0-9]+)*)"(?:, traits: \.fixedLayout\(width: (\d+), height: (\d+)\))?\) \{')


def preview_body(text, offset):
    """Read one balanced Swift builder, ignoring braces in strings and comments."""
    depth, index, state = 1, offset, 'code'
    while index < len(text):
        char, pair = text[index], text[index:index + 2]
        if state == 'string':
            if char == '\\':
                index += 2
                continue
            if char == '"':
                state = 'code'
        elif state == 'line':
            if char == '\n':
                state = 'code'
        elif state == 'comment':
            if pair == '*/':
                state = 'code'
                index += 2
                continue
        elif pair in ('//', '/*'):
            state = 'line' if pair == '//' else 'comment'
            index += 2
            continue
        elif char == '"':
            state = 'string'
        elif char == '{':
            depth += 1
        elif char == '}':
            depth -= 1
            if depth == 0:
                return textwrap.dedent(text[offset:index]).strip()
        index += 1
    raise ValueError('Unclosed preview builder')


def load_registry(root=APP_ROOT):
    registry = json.loads((root / 'screen-catalog.json').read_text())
    screens = []
    for source in sorted((root / 'Modules/Sources').glob('*/ScreenCatalogPreviewView.swift')):
        text = source.read_text().split(START)[0]
        for line in text.splitlines():
            if line.lstrip().startswith('#Preview') and not DECLARATION.match(line.strip()):
                raise ValueError(f'Unsupported catalog preview: {source}: {line}')
        for match in DECLARATION.finditer(text):
            identifier, width, height = match.groups()
            screens.append({'id': identifier, 'source': str(source.relative_to(root)),
                            'module': source.parent.name, 'width': int(width or 402),
                            'height': int(height or 874),
                            'body': preview_body(text, match.end()),
                            'capture': text[:match.start()].rstrip().split('\n')[-1].strip().startswith('// Screenshot: ')})
    ids = [screen['id'] for screen in screens]
    if not ids or len(ids) != len(set(ids)):
        raise ValueError('Catalog IDs must be nonempty and unique')
    registry['screens'] = [{key: value for key, value in screen.items() if key != 'capture'}
                           for screen in screens if screen['capture']]
    if not registry['screens']:
        raise ValueError('Select at least one preview with // Screenshot: <reason>')
    return registry


def generate(registry, root=APP_ROOT, check=False):
    stale = []
    for source in sorted((root / 'Modules/Sources').glob('*/ScreenCatalogPreviewView.swift')):
        module = source.parent.name
        text = source.read_text()
        if START in text:
            start, end = text.index(START), text.index(END) + len(END)
            text = text[:start] + text[end:]
        text = text.rstrip()
        if not text.endswith('#endif'):
            raise ValueError(f'Expected DEBUG catalog wrapper: {source}')
        entries = []
        for screen in registry['screens']:
            if screen['module'] != module:
                continue
            body = '\n'.join('                ' + line for line in screen['body'].splitlines())
            entries.append(f'            .init(id: "{screen["id"]}", size: CGSize(width: {screen["width"]}, height: {screen["height"]})) {{\n{body}\n            }}')
        generated = (START + '\n// Generated by scripts/screen-catalog.py --generate. Do not edit this section.\n'
                     f'@MainActor\nenum {module}ScreenSnapshotCatalog {{\n'
                     '    static var samples: [ScreenSnapshotSample] {\n'
                     '        [\n' + ',\n'.join(entries) + '\n        ]\n    }\n}\n' + END)
        expected = text[:-len('#endif')].rstrip() + '\n\n' + generated + '\n#endif\n'
        if source.read_text() != expected:
            stale.append(str(source.relative_to(root)))
            if not check:
                source.write_text(expected)
    if check and stale:
        raise ValueError('Regenerate snapshot factories: ' + ', '.join(stale))
    return stale


def png_size(data):
    if not data.startswith(b'\x89PNG\r\n\x1a\n'):
        raise ValueError('Not a PNG')
    offset, size, has_pixels = 8, None, False
    while offset + 12 <= len(data):
        length = struct.unpack('>I', data[offset:offset + 4])[0]
        kind = data[offset + 4:offset + 8]
        end = offset + 8 + length
        if end + 4 > len(data):
            raise ValueError('Truncated PNG')
        payload = data[offset + 8:end]
        if zlib.crc32(kind + payload) & 0xFFFFFFFF != struct.unpack('>I', data[end:end + 4])[0]:
            raise ValueError('PNG checksum mismatch')
        if kind == b'IHDR':
            size = struct.unpack('>II', payload[:8])
        if kind == b'IDAT':
            has_pixels = True
        if kind == b'IEND':
            if not size or min(size) < 200 or not has_pixels:
                raise ValueError('Missing or unexpectedly small PNG content')
            return size
        offset = end + 4
    raise ValueError('Incomplete PNG')


def publish(registry, captures, destination):
    expected = {screen['id']: screen for screen in registry['screens']}
    actual = {path.stem for path in captures.glob('*.png')}
    manifest = json.loads((captures / 'manifest.json').read_text())
    if actual != expected.keys() or set(manifest['ids']) != expected.keys() or len(manifest['ids']) != len(expected):
        raise ValueError('A complete successful snapshot batch is required')
    if manifest['renderer'] != 'Point-Free SnapshotTesting' or manifest['failures']:
        raise ValueError('Snapshot capture readiness or structural validation failed')
    for identifier, screen in expected.items():
        dimensions = png_size((captures / f'{identifier}.png').read_bytes())
        if dimensions != (screen['width'] * 3, screen['height'] * 3):
            raise ValueError(f'Wrong snapshot dimensions: {identifier}: {dimensions}')
    destination.mkdir(parents=True, exist_ok=True)
    for previous in destination.glob('*.png'):
        if previous.stem not in expected:
            previous.unlink()
    for identifier in expected:
        shutil.copyfile(captures / f'{identifier}.png', destination / f'{identifier}.png')
    return len(expected)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument('--generate', action='store_true')
    action.add_argument('--check', action='store_true')
    action.add_argument('--plan', action='store_true')
    action.add_argument('--publish', type=Path, metavar='CAPTURE_DIRECTORY')
    args = parser.parse_args()
    registry = load_registry()
    if args.generate or args.check:
        changed = generate(registry, check=args.check)
        print(f'{len(registry["screens"])} states; {len(changed)} factory files updated' if args.generate else 'Snapshot factories are current')
    elif args.plan:
        print(json.dumps([{key: value for key, value in screen.items() if key != 'body'} for screen in registry['screens']], indent=2))
    else:
        generate(registry, check=True)
        count = publish(registry, args.publish, APP_ROOT.parent / 'screenshots/current')
        print(f'Published {count} original-size PNGs; approved baselines preserved')


if __name__ == '__main__':
    main()
