func catalogSignInErrorState() -> SignUp.State {
    var state = SignUp.State()
    state.destination = .alert(AlertState<Never> {
        TextState("Login mislykkedes")
    } actions: {
        ButtonState(role: .cancel) { TextState("OK") }
    } message: {
        TextState("Prøv at logge ind igen.")
    })
    return state
}

@MainActor
func catalogSignInError() -> some View {
    ScreenCatalogContainerView {
        SignUpView(store: Store(initialState: catalogSignInErrorState()) {
            EmptyReducer<SignUp.State, SignUp.Action>()
                .ifLet(\.$destination, action: \.destination)
        })
    }
}

