#!/usr/bin/env python3
"""Export selected Xcode's skills once and expose them to both agent clients."""

import json
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
IGNORE_HEADER = '# Generated by scripts/update-xcode-skills.py\n'


def refresh(root=ROOT):
    destination = root / '.agents/apple-skills'
    destination.parent.mkdir(parents=True, exist_ok=True)
    directories = [root / '.agents/skills', root / '.claude/skills']
    with tempfile.TemporaryDirectory(prefix='apple-skills-', dir=destination.parent) as temporary:
        staged = Path(temporary) / 'export'
        subprocess.run(['xcrun', 'agent', 'skills', 'export', '--output-dir', str(staged)], check=True)
        names = sorted(path.name for path in staged.iterdir())
        if not names:
            raise ValueError('Xcode exported no skills')
        for name in names:
            skill = staged / name / 'SKILL.md'
            if (not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', name)
                    or not skill.is_file()
                    or not re.search(rf'(?m)^name:\s*{re.escape(name)}\s*$', skill.read_text())):
                raise ValueError(f'Invalid Apple skill: {name}')
        manifest = destination / '.inventory.json'
        if destination.exists() and not manifest.is_file():
            raise ValueError(f'Refusing to replace unmanaged Apple folder: {destination}')
        previous = json.loads(manifest.read_text()) if manifest.exists() else []
        if not isinstance(previous, list) or any(
            not isinstance(name, str) or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', name)
            for name in previous
        ):
            raise ValueError('Invalid Apple inventory')
        for directory in directories:
            ignore = directory / '.gitignore'
            if ignore.exists() and not ignore.read_text().startswith(IGNORE_HEADER):
                raise ValueError(f'Refusing to replace unrelated ignore file: {ignore}')
        (staged / '.inventory.json').write_text(json.dumps(names, indent=2) + '\n')
        backup = Path(temporary) / 'previous'
        if destination.exists():
            destination.rename(backup)
        try:
            staged.rename(destination)
        except OSError:
            if backup.exists():
                backup.rename(destination)
            raise
        for directory in directories:
            directory.mkdir(parents=True, exist_ok=True)
            for name in previous:
                alias = directory / name
                if alias.is_symlink() and alias.resolve() == (destination / name).resolve():
                    alias.unlink()
            for name in names:
                alias = directory / name
                if alias.resolve() != (destination / name).resolve() or not alias.is_symlink():
                    relative = Path('../apple-skills') if directory == directories[0] else Path('../../.agents/apple-skills')
                    alias.symlink_to(relative / name, target_is_directory=True)
            (directory / '.gitignore').write_text(IGNORE_HEADER + ''.join(f'/{name}\n' for name in names))
        print(f'Prepared {len(names)} shared Apple skills. Open a fresh agent session to discover them.')


if __name__ == '__main__':
    try:
        refresh()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        raise SystemExit(f'Apple skill refresh failed: {error}') from error
