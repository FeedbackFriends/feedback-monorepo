#!/usr/bin/env python3
"""Export Apple skills into the shared skills folder and link Claude discovery."""

import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
IGNORE_HEADER = '# Generated by scripts/shared/update-xcode-skills.py\n'
LEGACY_IGNORE_HEADER = '# Generated by scripts/update-xcode-skills.py\n'


def refresh(root=ROOT):
    skills = root / '.agents/skills'
    aliases = root / '.claude/skills'
    manifest = skills / '.apple-skills.json'
    previous = json.loads(manifest.read_text()) if manifest.exists() else []
    if not isinstance(previous, list) or any(
        not isinstance(name, str) or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', name)
        for name in previous
    ):
        raise ValueError('Invalid Apple inventory')
    with tempfile.TemporaryDirectory(prefix='apple-skills-') as temporary:
        staged = Path(temporary) / 'export'
        subprocess.run(['xcrun', 'agent', 'skills', 'export', '--output-dir', str(staged)], check=True)
        names = sorted(path.name for path in staged.iterdir())
        if not names:
            raise ValueError('Xcode exported no skills')
        for name in names:
            skill = staged / name / 'SKILL.md'
            if (not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', name)
                    or not skill.is_file()
                    or not re.search(rf'(?m)^name:\s*{re.escape(name)}\s*$', skill.read_text())):
                raise ValueError(f'Invalid Apple skill: {name}')
        for directory in (skills, aliases):
            directory.mkdir(parents=True, exist_ok=True)
            ignore = directory / '.gitignore'
            if ignore.exists() and not ignore.read_text().startswith((IGNORE_HEADER, LEGACY_IGNORE_HEADER)):
                raise ValueError(f'Refusing to replace unrelated ignore file: {ignore}')
        for name in previous:
            target = skills / name
            if target.exists():
                shutil.rmtree(target)
            alias = aliases / name
            if alias.is_symlink() and alias.resolve() == target.resolve():
                alias.unlink()
        # Save ownership before publishing so an interrupted refresh can be rerun.
        installed = []
        manifest.write_text('[]\n')
        for directory in (skills, aliases):
            (directory / '.gitignore').write_text(IGNORE_HEADER + ''.join(f'/{name}\n' for name in names))
        for name in names:
            (staged / name).rename(skills / name)
            installed.append(name)
            manifest.write_text(json.dumps(installed, indent=2) + '\n')
            (aliases / name).symlink_to(Path('../../.agents/skills') / name, target_is_directory=True)
        print(f'Prepared {len(names)} Apple skills in .agents/skills. Open a fresh session to discover them.')


if __name__ == '__main__':
    try:
        refresh()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        raise SystemExit(f'Apple skill refresh failed: {error}') from error
